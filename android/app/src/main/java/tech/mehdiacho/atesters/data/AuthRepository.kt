package tech.mehdiacho.atesters.data

import android.content.Context
import androidx.credentials.CredentialManager
import androidx.credentials.GetCredentialRequest
import com.google.android.libraries.identity.googleid.GetGoogleIdOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.firebase.auth.FirebaseUser
import com.google.firebase.auth.GoogleAuthProvider
import kotlinx.coroutines.channels.awaitClose
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.callbackFlow
import kotlinx.coroutines.tasks.await
import org.json.JSONObject
import tech.mehdiacho.atesters.BuildConfig
import java.util.UUID

/**
 * Google sign-in, with two paths.
 *
 * Against the emulator suite there is no OAuth client and no Play services account to
 * pick, so we hand the Auth emulator an unsigned ID token — a documented emulator feature
 * that exists precisely so a device can sign in without real Google infrastructure.
 *
 * Against the real project it is Credential Manager. The old GoogleSignInClient is
 * deprecated and being switched off, so it is deliberately not used here.
 */
object AuthRepository {

    private const val PREFS = "atesters.auth"
    private const val KEY_EMULATOR_UID = "emulator_uid"

    val currentUser: FirebaseUser? get() = FirebaseServices.auth.currentUser

    /** Emits on every sign-in and sign-out, including the initial state. */
    fun authState(): Flow<FirebaseUser?> = callbackFlow {
        val listener = com.google.firebase.auth.FirebaseAuth.AuthStateListener { trySend(it.currentUser) }
        FirebaseServices.auth.addAuthStateListener(listener)
        awaitClose { FirebaseServices.auth.removeAuthStateListener(listener) }
    }

    suspend fun signIn(context: Context): Result<Unit> = runCatching {
        val idToken = if (BuildConfig.USE_EMULATORS) {
            emulatorIdToken(context)
        } else {
            googleIdToken(context)
        }
        FirebaseServices.auth.signInWithCredential(GoogleAuthProvider.getCredential(idToken, null)).await()
        Unit
    }

    fun signOut() {
        FirebaseServices.auth.signOut()
    }

    // -----------------------------------------------------------------------

    private suspend fun googleIdToken(context: Context): String {
        // Generated by the google-services plugin — but only once an OAuth client exists,
        // which means Authentication enabled in the console and this build's SHA-1
        // registered. Resolved by name so a project without one fails with a sentence
        // someone can act on instead of a missing-symbol build error.
        val resId = context.resources.getIdentifier("default_web_client_id", "string", context.packageName)
        if (resId == 0) {
            error(
                "Google sign-in is not configured for this project yet: enable Authentication " +
                    "in the Firebase console, add this build's SHA-1, and re-download " +
                    "google-services.json.",
            )
        }

        val option = GetGoogleIdOption.Builder()
            .setServerClientId(context.getString(resId))
            .setFilterByAuthorizedAccounts(false)
            .setNonce(UUID.randomUUID().toString())
            .build()

        val response = CredentialManager.create(context)
            .getCredential(context, GetCredentialRequest.Builder().addCredentialOption(option).build())

        return GoogleIdTokenCredential.createFrom(response.credential.data).idToken
    }

    /**
     * The Auth emulator accepts an unsigned JSON payload where a real ID token would go.
     * The subject is kept in preferences so that reinstalling the app is a new tester but
     * relaunching it is the same one — otherwise every launch would orphan its seats.
     */
    private fun emulatorIdToken(context: Context): String {
        val prefs = context.getSharedPreferences(PREFS, Context.MODE_PRIVATE)
        val uid = prefs.getString(KEY_EMULATOR_UID, null) ?: UUID.randomUUID().toString().take(20).also {
            prefs.edit().putString(KEY_EMULATOR_UID, it).apply()
        }

        return JSONObject()
            .put("sub", uid)
            .put("email", "$uid@emulator.test")
            .put("email_verified", true)
            .put("name", "Emulator Tester")
            .toString()
    }
}
